
# Композиция промптов
# Установка личности LLM (будь то обычный командир карточки отряда или полководец фракции) производится через склеивание абстрактных принципов, 
# которые вместе формируют устойчивый паттерн личности и поведения.

# Вместо того чтобы хардкодить монолитные тексты на тысячи токенов, 
# мы собираем контекст динамически из нужных блоков.

# Например, полководец орков может быть представлен из следующих файлов:

# - l01_base/
#     mechanics/
#         economy.md - описание экономики игры, чтобы LLM понимала, что такое "ресурсы", "постройки", "юниты" и т.д.
#         strategic.md - описание глобальных правил игры.
#         (Важно: без tactical.md, ибо лорд фракции редко принимает сражения лично.)
#     format.md - общее описание ответов через Function Calling для каждого из персонажей
#     mechanics.md - описание механики игры, чтобы LLM понимала, что такое "юнит", "оружие", "урон" и т.д.
#     persona.md - Базовое описание, чем в общем виде является LLM - "Ты - персонаж игры Hex & Heresy, темное фентези, не ломай четвертую стену, ..."

# - l02_factions/ (сбор личной идентичности)
#     greenskins.md (личное описание, мол "Ты - орк, твоя раса любит громкие драки, ...")

# - l03_lore/ (сбор базы знаний персонажа)
#     (Знания собираются по принципу луковицы: вначале идут поверхностные знания, потом более глубокие и т.д.: они не противоречат друг другу, а дополняют.)
#     basic/
#         low.md
#         medium.md - базовые знания о мире, которые известны всем персонажам (например, "в мире есть магия, но часто она редка и опасна, также есть разные расы, которые воюют друг с другом, ...")
#     factions/
#         greenskins/
#             low.md
#             medium.md
#             high.md
#         Об остальных фракциях орки мало знают, поэтому их знания о них ограничены.
#     magic/
#         low.md - орки мало знают о магии, кроме самых простых проявлений в бою (за исключением шаманов, которые знают больше).

# - l04_roles/
#     lord.md - описание роли полководца, который управляет армией и принимает стратегические решения.

# l05_traits/
#     psychological/
#         sadist.md - описание архетипа "Садист".
#     tactical/
#         warmonger.md - описание архетипа "Разжигатель войн", который любит конфликты и провоцирует их, даже если это не всегда рационально.
#     unique/
#         backgrounds/
#             gladiator.md - описание архетипа "Гладиатор" (например, если конкретный полковodец раньше сражался на арене).

# Итог: к LLM попадает исчерпывающий контекст, который формирует полноценную личность, знания и цели персонажа.

# Правило разделения промптов: у каждой темы ровно один владелец.
# Блоки склеиваются в один контекст, поэтому повтор одной и той же информации в двух файлах — это
# потраченные токены и риск противоречий. Ответственность распределена так:
#   l1_base/mechanics/  — только правила игры (economy.md владеет содержанием войск и снабжением).
#   l2_factions/        — только идентичность ("кто ты и что ты ценишь"), без объяснения устройства мира.
#   l3_lore/basic/      — мир: небо и время, Катаклизм, обзор народов, ничья земля.
#   l3_lore/magic/      — резонит: колдовство, первичная взвесь, мутации и восемь проклятых генов.
#   l3_lore/factions/   — углубление по конкретной фракции поверх обзора из basic/.
#   l5_traits/          — личные черты персонажа (в т.ч. его собственный проклятый ген), а не знания о мире.
# Внутри одной папки уровни low -> medium -> high -> max тоже не пересказывают друг друга: каждый следующий
# уровень добавляет новый слой поверх предыдущих.
