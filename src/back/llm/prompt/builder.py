


# Композиция промптов
# Установка личности LLM (будь то обычный командир карточки отряда или полководец фракции) производится через склеивание абстрактных принципов, 
# которые вместе формируют устойчивый паттерн личности и поведения.

# Вместо того чтобы хардкодить монолитные тексты на тысячи токенов, 
# мы собираем контекст динамически из нужных блоков.

# Например, возьмем полководца расы орков и личности "Разжигатель войны".
# Как формируется его личность?

# Строго по слоям (l01-l05):
# l01_core: - базовые инструкции.
# l02_world: - общие правила мира.
# l03_faction: - правила фракции (например, расы орков).
# l04_roles: - роли (например, полководец).
# l05_traits: - архетипы (например, "Разжигатель войны").



# Например, для главы зелекожих промпт билдер собирает:

# l1/
    # base_persona.md (базовые инструкции по поведению LLM)
    # forman_json.md (инструкции по формату JSON для LLM)
    # mechanics.md (правила механики игры, которые LLM должен учитывать при генерации ответов)

# l2/
    # lore.md (правила мира, которые LLM должен учитывать при генерации ответов)
    # magic.md (описание магической системы)

# l3/
    # orcs.md (правила поведения орков)

# l4/
    # lord.md (описание роли полководца)

# l5/
    # warmonger.md (описание архетипа "Разжигатель войны")